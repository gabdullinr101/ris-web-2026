-- Схема базы: бронирование тренировок (ЛР9)
-- Таблицы и связи как в docs/data-model.md (ЛР2): halls ← bookings → users.
-- Запуск: psql -U postgres -d fitness_bookings -f db/schema.sql
-- Скрипт можно прогонять повторно: в начале он удаляет только свои три таблицы.
-- Это учебное пересоздание схемы, а не команда приложения: DELETE в API не используется.

DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS halls CASCADE;

-- Справочник залов клуба. Название зала хранится только здесь (3НФ).
CREATE TABLE halls (
    id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);

-- Пользователи: администратор ресепшн, тренер, управляющий клуба.
CREATE TABLE users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         text NOT NULL UNIQUE,
    full_name     text NOT NULL,
    role          text NOT NULL
                  CHECK (role IN ('Admin', 'Trainer', 'Manager')),
    -- hash пароля появится в ЛР11 (его посчитает сервер библиотекой).
    -- Открытый пароль здесь не хранится никогда.
    password_hash text NULL
);

-- Записи на тренировку - главный объект.
CREATE TABLE bookings (
    id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- человеческий номер, например БР-0001; не замена id
    number             text NOT NULL UNIQUE,
    title              text NOT NULL
                       CHECK (char_length(title) BETWEEN 5 AND 80),
    description        text NOT NULL
                       CHECK (char_length(description) BETWEEN 10 AND 500),
    -- ссылка на зал, а не его название
    hall_id            integer NOT NULL REFERENCES halls (id),
    status             text NOT NULL DEFAULT 'New'
                       CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at         timestamptz NOT NULL DEFAULT now(),
    created_by_user_id integer NOT NULL REFERENCES users (id),
    -- у новой записи тренера может не быть: NULL, а не 0
    assignee_user_id   integer NULL REFERENCES users (id)
);

-- зачем: список и сводка фильтруются по статусу (WHERE status = 'New', GROUP BY status)
CREATE INDEX bookings_status_idx ON bookings (status);

-- зачем: соединение с залами (JOIN halls ON halls.id = bookings.hall_id) и выборка записей одного зала
CREATE INDEX bookings_hall_id_idx ON bookings (hall_id);

-- зачем: тренер видит только свои записи (WHERE assignee_user_id = ...), см. ФТ-5 в ЛР1
CREATE INDEX bookings_assignee_user_id_idx ON bookings (assignee_user_id);

-- зачем: внешний ключ на создателя записи; такой же индекс создаёт миграция EF Core (ЛР10)
CREATE INDEX bookings_created_by_user_id_idx ON bookings (created_by_user_id);
